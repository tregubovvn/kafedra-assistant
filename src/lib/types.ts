// Типы, общие для клиента и API

export interface AppUser {
  id: number
  email: string
  fullName: string
  role: 'HEAD' | 'TEACHER'
  position?: string | null
  degree?: string | null
}

export interface WorkItem {
  id: number
  userId: number
  userFullName: string
  title: string
  date: string
  type: string
  description: string
  authorDescription: string
  newsUrl: string | null
  replacementId: number | null
  autoGenerated: boolean
  createdAt: string
}

export interface AssignmentStatusInfo {
  teacherId: number
  teacherFullName: string
  completed: boolean
  completedAt: string | null
  result: string
}

export interface AssignmentItem {
  id: number
  title: string
  description: string
  completionCriteria: string
  dueDate: string
  dueTime: string
  requireResult: boolean
  forAll: boolean
  createdAt: string
  statuses: AssignmentStatusInfo[]
}

export interface ReplacementRequestInfo {
  id: number
  teacherId: number
  teacherFullName: string
  status: string
}

export interface ReplacementItem {
  id: number
  discipline: string
  groupId: string
  kind: string
  room: string | null
  lessonDate: string
  pairNumber: number
  initiatorId: number
  initiatorFullName: string
  substituteId: number | null
  substituteFullName: string | null
  status: string
  assignedByHead: boolean
  createdAt: string
  requests: ReplacementRequestInfo[]
}

export interface IncomingRequest {
  requestId: number
  replacement: ReplacementItem
}

export interface ScheduleLesson {
  pairNumber: number
  start: string
  end: string
  discipline: string
  kind: string
  groupId: string
  room: string | null
  teacherName?: string | null
  isSubstitution?: boolean
  replacedBy?: string | null
  searching?: boolean
}

export interface Candidate {
  id: number
  fullName: string
  role: string
  detail: string
}

export interface CandidateGroup {
  key: 'next' | 'prev' | 'free' | 'other'
  label: string
  teachers: Candidate[]
}

export interface MailItem {
  id: number
  toEmail: string
  toName: string
  type: string
  subject: string
  body: string
  createdAt: string
}

export interface RaspLesson {
  teacherName: string
  date: string
  pairNumber: number
  discipline: string
  kind: string
  groupId: string
  room: string
}