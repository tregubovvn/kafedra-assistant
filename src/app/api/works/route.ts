import { NextResponse } from 'next/server'
import { db } from '@/lib/db'
import { getSessionUser } from '@/lib/server/auth'
import { isValidDateStr, WORK_TYPES, todayStr } from '@/lib/schedule'

// Журнал работ: преподаватель видит свои, заведующий — все с фильтрами
export async function GET(req: Request) {
  const me = await getSessionUser(req)
  if (!me) return NextResponse.json({ error: 'Не авторизован' }, { status: 401 })

  const url = new URL(req.url)
  const mine = url.searchParams.get('mine') === '1'
  const teacherId = url.searchParams.get('teacherId')
  const month = url.searchParams.get('month') // YYYY-MM
  const type = url.searchParams.get('type')

  const where: Record<string, unknown> = {}
  if (mine || me.role === 'TEACHER') {
    where.userId = me.id
  } else if (teacherId && Number.isInteger(Number(teacherId))) {
    where.userId = Number(teacherId)
  }
  if (month && /^\d{4}-\d{2}$/.test(month)) where.date = { startsWith: month }
  if (type && (WORK_TYPES as readonly string[]).includes(type)) where.type = type

  const works = await db.work.findMany({
    where,
    orderBy: [{ date: 'desc' }, { id: 'desc' }],
    include: { user: { select: { fullName: true } } },
    take: 500,
  })

  return NextResponse.json({
    works: works.map((w) => ({
      id: w.id,
      userId: w.userId,
      userFullName: w.user.fullName,
      date: w.date,
      type: w.type,
      description: w.description,
      newsUrl: w.newsUrl,
      replacementId: w.replacementId,
      autoGenerated: w.autoGenerated,
      createdAt: w.createdAt.toISOString(),
    })),
  })
}

// Добавление записи о выполненной работе
export async function POST(req: Request) {
  const me = await getSessionUser(req)
  if (!me) return NextResponse.json({ error: 'Не авторизован' }, { status: 401 })

  const body = await req.json().catch(() => null)
  const date = body?.date
  const type = body?.type
  const description = typeof body?.description === 'string' ? body.description.trim() : ''
  const newsUrl = typeof body?.newsUrl === 'string' && body.newsUrl.trim() ? body.newsUrl.trim() : null

  if (!isValidDateStr(date)) return NextResponse.json({ error: 'Укажите дату' }, { status: 400 })
  if (!(WORK_TYPES as readonly string[]).includes(type)) {
    return NextResponse.json({ error: 'Выберите вид работы' }, { status: 400 })
  }
  if (description.length < 3) return NextResponse.json({ error: 'Опишите выполненную работу' }, { status: 400 })
  if (newsUrl && !/^https?:\/\//.test(newsUrl)) {
    return NextResponse.json({ error: 'Ссылка на новость должна начинаться с http:// или https://' }, { status: 400 })
  }
  if (date > todayStr()) {
    return NextResponse.json({ error: 'Дата работы не может быть в будущем' }, { status: 400 })
  }

  const work = await db.work.create({
    data: { userId: me.id, date, type, description, newsUrl },
  })
  return NextResponse.json({ work })
}
