-- Схема БД «Ассистент кафедры ПМН» (PostgreSQL / Supabase).
-- Применяется скриптом scripts/db-push.mjs (`npm run db:push`).
-- Все объекты создаются с IF NOT EXISTS — повторный запуск безопасен.

create table if not exists "User" (
    id             serial primary key,
    email          text not null unique,
    "passwordHash" text not null,
    "fullName"     text not null,
    role           text not null,
    position       text not null default '',
    degree         text not null default '',
    "createdAt"    timestamptz(3) not null default now()
);

-- для баз, созданных до появления колонок
alter table "User" add column if not exists position text not null default '';
alter table "User" add column if not exists degree text not null default '';

create table if not exists "Session" (
    id          serial primary key,
    token       text not null unique,
    "userId"    integer not null references "User" (id) on delete cascade,
    "createdAt" timestamptz(3) not null default now()
);

create table if not exists "Work" (
    id              serial primary key,
    "userId"        integer not null references "User" (id) on delete cascade,
    date            text not null,
    type            text not null,
    description     text not null,
    "newsUrl"       text,
    "replacementId" integer,
    "autoGenerated" boolean not null default false,
    "createdAt"     timestamptz(3) not null default now()
);

create index if not exists "Work_userId_date_idx" on "Work" ("userId", date);

create table if not exists "Assignment" (
    id          serial primary key,
    description text not null,
    "dueDate"   text not null,
    "forAll"    boolean not null default false,
    "createdBy" integer not null,
    "createdAt" timestamptz(3) not null default now()
);

create index if not exists "Assignment_dueDate_idx" on "Assignment" ("dueDate");

create table if not exists "AssignmentStatus" (
    id             serial primary key,
    "assignmentId" integer not null references "Assignment" (id) on delete cascade,
    "teacherId"    integer not null references "User" (id) on delete cascade,
    completed      boolean not null default false,
    "completedAt"  timestamptz(3),
    unique ("assignmentId", "teacherId")
);

create table if not exists "Replacement" (
    id               serial primary key,
    discipline       text not null,
    "groupId"        text not null,
    kind             text not null,
    room             text,
    "lessonDate"     text not null,
    "pairNumber"     integer not null,
    "initiatorId"    integer not null references "User" (id) on delete cascade,
    "substituteId"   integer references "User" (id) on delete set null,
    status           text not null default 'SEARCHING',
    "assignedByHead" boolean not null default false,
    "createdAt"      timestamptz(3) not null default now()
);

create index if not exists "Replacement_lessonDate_idx" on "Replacement" ("lessonDate");

create table if not exists "ReplacementRequest" (
    id              serial primary key,
    "replacementId" integer not null references "Replacement" (id) on delete cascade,
    "teacherId"     integer not null references "User" (id) on delete cascade,
    status          text not null default 'PENDING',
    "createdAt"     timestamptz(3) not null default now(),
    unique ("replacementId", "teacherId")
);

create table if not exists "ScheduleEntry" (
    id            serial primary key,
    "ownerType"   text not null,
    "ownerId"     text not null,
    date          text not null,
    "pairNumber"  integer not null,
    discipline    text not null,
    kind          text not null,
    "groupId"     text not null,
    room          text,
    "teacherName" text
);

create index if not exists "ScheduleEntry_ownerType_ownerId_date_idx"
    on "ScheduleEntry" ("ownerType", "ownerId", date);

-- Singleton: всегда одна строка с id = 1
create table if not exists "Settings" (
    id               integer primary key default 1,
    "deepseekApiKey" text not null default ''
);

create table if not exists "MailLog" (
    id          serial primary key,
    "toEmail"   text not null,
    "toName"    text not null,
    type        text not null,
    subject     text not null,
    body        text not null,
    "createdAt" timestamptz(3) not null default now()
);
